//! Issue-report bundles: a redacted zip a user can attach to a bug report.

use std::fs::OpenOptions;
use std::io::Write;
use std::os::unix::fs::OpenOptionsExt;
use std::path::PathBuf;

use serde_json::{Value, json};
use wa_core::config::Paths;
use wa_core::time::{epoch_to_rfc3339, now_epoch};
use wa_core::{AppError, Result};
use zip::write::SimpleFileOptions;

use crate::issues::IssueStore;
use crate::query::tail_raw_lines;
use crate::redact::redact;

/// Log lines included in a bundle.
pub const BUNDLE_LOG_LINES: usize = 2000;

const README: &str = "wa-desk issue report
====================

This archive was generated by wa-desk to help diagnose a problem.

  system.json   OS, app version and app-provided context
  issues.json   the selected issues (deduplicated problems)
  logs/recent.jsonl   the most recent log lines

Everything was redacted before it was written: access tokens, bearer values,
phone numbers (only the last 4 digits are kept) and your home folder path.
No databases, message contents files or the bridge token are included.
";

/// Scrubs text with the standard redactor plus the literal bridge token.
struct Scrubber {
    token: Option<String>,
}

impl Scrubber {
    fn new(paths: &Paths) -> Self {
        let token = std::fs::read_to_string(&paths.token_file)
            .ok()
            .map(|t| t.trim().to_string())
            .filter(|t| t.len() >= 8);
        Self { token }
    }

    fn clean(&self, s: &str) -> String {
        let s = match &self.token {
            Some(t) => s.replace(t.as_str(), "[redacted]"),
            None => s.to_string(),
        };
        redact(&s)
    }
}

fn os_release() -> Option<String> {
    let text = std::fs::read_to_string("/etc/os-release").ok()?;
    text.lines()
        .find_map(|l| l.strip_prefix("PRETTY_NAME="))
        .map(|v| v.trim_matches('"').to_string())
}

fn system_json(extra: &Value) -> Value {
    let app_version = extra
        .get("app_version")
        .and_then(Value::as_str)
        .unwrap_or(env!("CARGO_PKG_VERSION"))
        .to_string();
    json!({
        "os": std::env::consts::OS,
        "arch": std::env::consts::ARCH,
        "distro": os_release(),
        "kernel": std::fs::read_to_string("/proc/sys/kernel/osrelease").ok().map(|s| s.trim().to_string()),
        "app_version": app_version,
        "generated_at": epoch_to_rfc3339(now_epoch()),
        "extra": extra,
    })
}

fn unique_zip_path(paths: &Paths) -> PathBuf {
    let stamp = chrono::Local::now().format("%Y%m%d-%H%M%S");
    let base = format!("wa-desk-report-{stamp}");
    let mut p = paths.exports.join(format!("{base}.zip"));
    let mut n = 1;
    while p.exists() {
        n += 1;
        p = paths.exports.join(format!("{base} ({n}).zip"));
    }
    p
}

/// Write a redacted zip into `Paths.exports` with README.txt, system.json,
/// issues.json (only `ids` if given) and the last 2000 log lines.
/// Never includes the token file or any database.
pub fn export_bundle(
    paths: &Paths,
    issues: &IssueStore,
    ids: Option<&[i64]>,
    extra: Value,
) -> Result<PathBuf> {
    std::fs::create_dir_all(&paths.exports)?;
    let scrub = Scrubber::new(paths);
    let all = issues.list()?;
    let selected: Vec<_> = match ids {
        Some(ids) => all.into_iter().filter(|i| ids.contains(&i.id)).collect(),
        None => all,
    };
    let issues_text = scrub.clean(&serde_json::to_string_pretty(&selected)?);
    let system_text = scrub.clean(&serde_json::to_string_pretty(&system_json(&extra))?);
    let logs: Vec<String> = tail_raw_lines(&paths.logs, BUNDLE_LOG_LINES)
        .iter()
        .map(|l| scrub.clean(l))
        .collect();
    let mut logs_text = logs.join("\n");
    logs_text.push('\n');

    let path = unique_zip_path(paths);
    let file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(&path)?;
    let mut zip = zip::ZipWriter::new(file);
    let opts = SimpleFileOptions::default()
        .compression_method(zip::CompressionMethod::Deflated)
        .unix_permissions(0o600);
    let zerr = |e: zip::result::ZipError| {
        AppError::internal("could not write report").with_detail(e.to_string())
    };
    for (name, body) in [
        ("README.txt", README.to_string()),
        ("system.json", system_text),
        ("issues.json", issues_text),
        ("logs/recent.jsonl", logs_text),
    ] {
        zip.start_file(name, opts).map_err(zerr)?;
        zip.write_all(body.as_bytes())?;
    }
    zip.finish().map_err(zerr)?;
    tracing::info!(
        issues = selected.len(),
        lines = logs.len(),
        "exported issue bundle"
    );
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Read;
    use wa_core::ErrorKind;
    use wa_testkit::{Fixture, TOKEN};

    fn read_zip(p: &std::path::Path) -> Vec<(String, String)> {
        let mut z = zip::ZipArchive::new(std::fs::File::open(p).unwrap()).unwrap();
        (0..z.len())
            .map(|i| {
                let mut f = z.by_index(i).unwrap();
                let mut s = String::new();
                f.read_to_string(&mut s).unwrap();
                (f.name().to_string(), s)
            })
            .collect()
    }

    #[test]
    fn bundle_never_contains_token() {
        let fx = Fixture::new();
        let p = &fx.paths;
        std::fs::create_dir_all(&p.logs).unwrap();
        let line = |m: &str| {
            json!({"timestamp":"2026-11-16T10:00:00Z","level":"ERROR","target":"wa_bridge","fields":{"message": m}}).to_string()
        };
        let lines = [
            line(&format!("raw token {TOKEN}")),
            line(&format!("Authorization: Bearer {TOKEN}")),
            line("from 919811111234 in /tmp/x"),
            format!("corrupt {TOKEN}"),
        ];
        std::fs::write(p.logs.join("wa-desk.2026-11-16.jsonl"), lines.join("\n")).unwrap();
        let store = IssueStore::open(p).unwrap();
        let (i, _) = store
            .record_issue(
                ErrorKind::Auth,
                "bridge",
                "token rejected",
                Some(&format!("used {TOKEN}")),
            )
            .unwrap();
        store
            .record_issue(ErrorKind::Busy, "db", "other", None)
            .unwrap();
        let zip = export_bundle(
            p,
            &store,
            Some(&[i.id]),
            json!({"note": TOKEN, "app_version": "9.9.9"}),
        )
        .unwrap();
        assert!(zip.starts_with(&p.exports));

        let raw = std::fs::read(&zip).unwrap();
        assert!(!raw.windows(TOKEN.len()).any(|w| w == TOKEN.as_bytes()));
        let entries = read_zip(&zip);
        let names: Vec<_> = entries.iter().map(|(n, _)| n.as_str()).collect();
        assert_eq!(
            names,
            [
                "README.txt",
                "system.json",
                "issues.json",
                "logs/recent.jsonl"
            ]
        );
        for (name, body) in &entries {
            assert!(!body.contains(TOKEN), "{name} leaks token");
            assert!(!body.contains(&TOKEN[..20]), "{name} leaks token prefix");
            assert!(!body.contains("919811111234"), "{name} leaks phone");
        }
        let issues: Vec<Value> = serde_json::from_str(&entries[2].1).unwrap();
        assert_eq!(issues.len(), 1);
        let sys: Value = serde_json::from_str(&entries[1].1).unwrap();
        assert_eq!(sys["app_version"], "9.9.9");
        assert_eq!(sys["os"], "linux");
        assert_eq!(entries[3].1.lines().count(), 4);
        let mode = std::os::unix::fs::PermissionsExt::mode(
            &std::fs::metadata(&zip).unwrap().permissions(),
        );
        assert_eq!(mode & 0o777, 0o600);
    }

    #[test]
    fn short_or_custom_token_also_scrubbed() {
        let fx = Fixture::new();
        let p = &fx.paths;
        // A non-hex token the generic redactor would not catch.
        std::fs::write(&p.token_file, "Zq9-not-hex-secret!\n").unwrap();
        std::fs::create_dir_all(&p.logs).unwrap();
        std::fs::write(
            p.logs.join("wa-desk.2026-11-16.jsonl"),
            "leak Zq9-not-hex-secret! here\n",
        )
        .unwrap();
        let store = IssueStore::in_memory().unwrap();
        let a = export_bundle(p, &store, None, json!({})).unwrap();
        let b = export_bundle(p, &store, None, json!({})).unwrap();
        assert_ne!(a, b, "unique names");
        for (_, body) in read_zip(&a) {
            assert!(!body.contains("Zq9-not-hex-secret!"));
        }
    }
}
